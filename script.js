function showImpact(majorKey) {
const major = majors[majorKey];

const impactContent = document.getElementById("impactContent");

let cards = "";

major.impacts.forEach((impact, index) => {

    cards += `
        <div class="impact-card">

            <span>
                &gt; IMPACT_0${index + 1}
            </span>

            <h3>
                ${impact.title}
            </h3>

            <p>
                ${impact.text}
            </p>

        </div>
    `;

});


impactContent.innerHTML = `

    <div class="impact-header">

        <span>
            &gt; selected_major
        </span>

        <h2>
            ${major.name}
        </h2>

        <p>
            ${major.description}
        </p>

    </div>


    <div class="impact-grid">

        ${cards}

    </div>

`;


document.getElementById("impact")
    .scrollIntoView({
        behavior: "smooth"
    });
}